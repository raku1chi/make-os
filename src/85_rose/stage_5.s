stage_5:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始
		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; フォントプロトコルを取得
		;---------------------------------------
		xcall	get_protocol, [EFI_HII_FONT_PROTOCOL_GUID]
		mov		[gHFP], rax						; gHFP = get_protocol();

		mov		rcx, [gHFP]						; RCX = gHFP;
		xcall	htoa, rcx, [.proto], 17			; htoa();

		xcall	puts, [.s0]						; puts();

		;---------------------------------------
		; フォントを取得
		;---------------------------------------
		xcall	get_font						; get_font();
		xcall	put_glyph, qword 'A'			; put_glyph();

		;---------------------------------------
		; キー入力待ち
		;---------------------------------------
		xcall	puts, [Const.PressAnyKey]		; puts();
		xcall	read_key						; read_key();
		xcall	puts, [Const.ClearMessage]		; puts();

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了

;========================================================================
[section .data]
ALIGN 16, db 0
.s0:		db	"PROTOCOL", 0x0D, 0x0A
			db	" FONT = "
.proto:		db	"12345678_12345678", 0x0D, 0x0A, 0

;========================================================================
[section .text]
