;■引数		: 無し
;
;■戻り値	: 無し
;************************************************************************
stage_4:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始

		; ローカル変数の定義
		%local	ptr_alloc:qword					; void* ptr_alloc;

		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; メモリの確保
		;---------------------------------------
		xcall	allocate_pool, 100				; RAX = allocate_pool();
		mov		[ptr_alloc], rax				; ptr_alloc = RAX;

		;---------------------------------------
		; アドレスの表示
		;---------------------------------------
		mov		rcx, [ptr_alloc]				; RCX = ptr_alloc;
		xcall	htoa, rcx, [.s0_ptr], 17		; htoa();
		xcall	puts, [.s0]						; puts();

		;---------------------------------------
		; メモリの解放
		;---------------------------------------
		xcall	free_pool, qword [ptr_alloc]	; free_pool();

		;---------------------------------------
		; キー入力待ち
		;---------------------------------------
		xcall	puts, [Const.PressAnyKey]		; puts();
		xcall	read_key						; read_key();
		xcall	puts, [Const.ClearMessage]		; puts();

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了

;========================================================================
[section .data]
.s0:		db	"Memory Allocate", 0x0D, 0x0A
			db	" Address : "
.s0_ptr:	db	"12345678_12345678", 0x0D, 0x0A, 0

;========================================================================
[section .text]
