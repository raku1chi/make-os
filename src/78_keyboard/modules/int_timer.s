;************************************************************************
;	タイマー割り込み
;************************************************************************
int_timer:
		;---------------------------------------
		; 【レジスタの保存】
		;---------------------------------------
		push_all								; // レジスタの保存

		;---------------------------------------
		; 割り込みフラグをクリア(EOI)
		;---------------------------------------
		mov		rax, [APIC.Base]				; 
		mov		LAPIC(rax, .EOI), 0				; LAPIC.EOI = 0;

		;---------------------------------------
		; TICK
		;---------------------------------------
		inc		qword [Timer.Counter]			; Timer.Counter++;

		;---------------------------------------
		; 【レジスタの復帰】
		;---------------------------------------
		pop_all									; // レジスタの復帰
		iretq
