;************************************************************************
;	スタックフレームの定義
;************************************************************************
;---------------------------------------
; スタックフレーム開始
;---------------------------------------
%macro	FRAME_BEGIN 0
		%push							; // コンテキストの設定
		%stacksize	flat64				; // スタック幅を設定
		%assign		%$localsize (8 * 6)	; // スタック数を初期化
%endmacro

;---------------------------------------
; スタックの調整
;---------------------------------------
%macro	FRAME_STACK 0
		push	rbp						; // RBPを保存
		mov		rbp, rsp				; // RBPの再設定
		sub		rsp, %$localsize		; // スタック領域の確保
		and		rsp, ~0x0F				; // 16バイト境界に設定
%endmacro

;---------------------------------------
; スタックフレーム終了
;---------------------------------------
%macro	FRAME_END 0
		mov		rsp, rbp				; // RSPの復帰
		pop		rbp						; // RBPの復帰
		ret
		%pop
%endmacro
