;************************************************************************
;	IDTの初期化
;========================================================================
;■書式		: void init_idt(void);
;
;■引数		: 無し
;
;■戻り値	: 無し
;************************************************************************
init_idt:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始
		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; IDTの設定
		;---------------------------------------
		; 先頭のエントリを設定
		lea		rcx, [int_stop]					; // デフォルトの割り込み
		mov		[IDT + 0], cx					; // Offset[15:0]
		mov		cx, 0x8E00						; // TYPE
		mov		[IDT + 4], rcx					; // Offset[63:16]
		mov		[IDT + 2], cs					; // Code Segment

		; 先頭のエントリをコピー元とする
		mov		r8d, [IDT + 8]					; R8 = 上位8バイト;
		mov		r9, [IDT + 0]					; R9 = 下位8バイト;

		; IDTの設定
		lea		rdx, [IDT]						; ptr = &IDT[0];
		mov		rcx, 256						; RCX = 256; // 256エントリ
.10L:											; do
												; {
		mov		[rdx + 8], r8					;   *ptr.hi = R8;
		mov		[rdx + 0], r9					;   *ptr.lo = R9;
		add		rdx, 16							;   ptr++;
		loop	.10L							; } while (--RCX);

		; IDTRの設定
		lea		rcx, [IDT]						; // IDTの先頭
		mov		[IDTR.Base], rcx				; IDTR.Base = &IDT[0];
		mov		word [IDTR.Limit], (16 * 256) - 1

		lidt	[IDTR]							; // 割り込みディスクリプタテーブルをロード

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了
