;************************************************************************
;	フレームバッファ情報を表示
;========================================================================
;■書式		: void put_gop_mode(void);
;
;■引数		: 無し
;
;■戻り値	: 無し
;************************************************************************
put_gop_mode:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始
		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; フレームバッファアドレス／サイズを表示
		;---------------------------------------
		mov		rcx, [Video.FrameBufferBase]	; RCX = FrameBufferBase;
		xcall	htoa, rcx, [.base], 17			; htoa();
		mov		rcx, [Video.FrameBufferSize]	; RCX = FrameBufferSize;
		xcall	htoa, rcx, [.size], 17			; htoa();

		xcall	puts, [.s0]						; puts();

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了

;========================================================================
[section .data]
ALIGN 16, db 0
.s0:		db	" FrameBufferBase      : "
.base:		db	"12345678_12345678", 0x0D, 0x0A
			db	" FrameBufferSize      : "
.size:		db	"12345678_12345678", 0x0D, 0x0A, 0

;========================================================================
[section .text]
