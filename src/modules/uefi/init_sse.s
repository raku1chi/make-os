;************************************************************************
;	SSEの初期化
;========================================================================
;■書式		: void init_sse();
;
;■引数		: 無し
;
;■戻り値	: 無し
;************************************************************************
init_sse:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始
		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; SSE2を有効化
		;---------------------------------------
		; SSE2を有効化（CR0）
		mov		rax, cr0						; RAX = CR0;
		or		rax,  (1 << 1)					; MP = 1;
		and		rax, ~(1 << 2)					; EM = 0;
		or		rax,  (1 << 3)					; TS = 1;
		mov		cr0, rax						; CR0 = RAX

		; SSE2を有効化（CR4）
		mov		rax, cr4						; RAX = CR4;
		or		rax, (1 << 9)					; OSFXSR = 1;
		mov		cr4, rax						; CR4 = RAX;

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了
