;************************************************************************
;	ウェイト
;========================================================================
;■書式		: void wait(tick);
;
;■引数
;	tick	: システム割り込み回数
;
;■戻り値	: 無し
;************************************************************************
wait_tick:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始
		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; ウェイト
		;---------------------------------------
		mov		rax, [Timer.Counter]			; RAX = カウンタ値;
.10L:											; do
												; {
		cmp		[Timer.Counter], rax			;   while (Counter == RAX)
		je		.10L							;     ;
		inc		rax								;   RAX++;
		loop	.10L							; } while (--RCX);

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了
