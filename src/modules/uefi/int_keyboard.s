;************************************************************************
;	割り込み処理：キーボード
;------------------------------------------------------------------------
;	KBC（キーボードコントローラ）からキーコードを取得して、
;	専用のリングバッファに保存する。
;************************************************************************
int_keyboard:
		;---------------------------------------
		; レジスタの保存
		;---------------------------------------
		push_all								; // レジスタの保存
		push	rbp								; // RBPを保存
		mov		rbp, rsp						; // RBPの再設定

		; シャドウスペースの確保
		sub		rsp, (8 * 6)					; // シャドウスペースの確保
		and		rsp, ~0x0F						; // 16バイト境界に設定

		;---------------------------------------
		; KBCのバッファ読み取り
		;---------------------------------------
		in		al, 0x60						; AL = キーコードの取得

		;---------------------------------------
		; キーコードの保存
		;---------------------------------------
		xcall	ring_wr, KEY_BUFF, rax			; ring_wr();

		;---------------------------------------
		; 割り込み終了コマンド送信
		;---------------------------------------
		outp	0x20, 0x20						; outp(); // マスタPIC:EOIコマンド

		;---------------------------------------
		; レジスタの復帰
		;---------------------------------------
		mov		rsp, rbp						; // RSPの復帰
		pop		rbp								; // RBPの復帰
		pop_all									; // レジスタの復帰
		iretq

;========================================================================
[section .data]
ALIGN 16, db 0
KEY_BUFF:	times ring_buff_size db 0

;========================================================================
[section .text]
