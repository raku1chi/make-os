;************************************************************************
;	デフォルトの割り込み（復帰しない）
;************************************************************************
int_stop:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始
		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; タイトル行を表示
		;---------------------------------------
		mov		r12, [Video.HorizontalResolution]; // エラーメッセージ表示位置（列）
		sub		r12, COL(TITLE_LEN)				; R12 = 横幅 - タイトル表示幅;
		shr		r12, 1							; R12 /= 2;
		mov		r13, [Video.VerticalResolution]	; // エラーメッセージ表示位置（行）
		sub		r13, ROW(8)						; R13 = 縦幅 - 8行分;
		shr		r13, 1							; R13 /= 2;
		mov		r14, 8 * 1						; 開始オフセット値
		mov		r15, 8 * 6						; 最終オフセット値

		xcall	draw_str, r12, r13, \
					COLOR_WHITE, COLOR_RED, \
					[.s0]						; draw_str();

		;---------------------------------------
		; スタックの内容を表示
		;---------------------------------------
.10L:	cmp		r14, r15						; while (R14 < R15)
		jae		.10E							; {
												;   // インデックス
		xcall	htoa, r14, [.offset], 2			;   htoa();

		mov		rcx, [rbp + r14]				;   //スタックの値
		xcall	htoa, rcx, [.value], 17			;   htoa();

		add		r13, CHAR_HEIGHT				;   // 1行下げる
		xcall	draw_str, r12, r13, \
					COLOR_RED, COLOR_WHITE, \
					[.s1]						;   // 行全体を表示
		add		r14, 8							;   R14 += 8; // 次のデータ
		jmp		.10L							; }
.10E:											; 

		jmp		$								; while (1) ; // 無限ループ

		FRAME_END								; // フレームの終了

.s0:		db		" <         STOP         > ", 0
TITLE_LEN	equ		($ - .s0) - 1

;========================================================================
[section .data]
ALIGN 16, db 0
.s1:		db		" RBP+"
.offset:	db		"12", ":"
.value:		db		"12345678_12345678", " ", 0

;========================================================================
[section .text]
