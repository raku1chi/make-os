;************************************************************************
;	TSSの初期化
;========================================================================
;■書式		: void init_tss();
;
;■引数		: 無し
;
;■戻り値	: 無し
;************************************************************************
init_tss:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始
		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; マルチタスクの設定
		;---------------------------------------
		lea		rcx, [Task.Kernel]				; // 最初に実行するタスク
		mov		qword [Task.Current], rcx		; CURRENT_TASK = &TASK_0;

		; TSSの設定
		set_tss	[NEW_GDT.tss], [Task.TSS]		; // TSSの設定

		; タスクレジスタの設定
		mov		ax, TSS_TASK					; 
		ltr		ax								; // タスクレジスタの設定

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了
