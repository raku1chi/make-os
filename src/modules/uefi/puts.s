;************************************************************************
;	文字列を出力
;========================================================================
;■書式		: void puts(str);
;
;■引数
;	str		: 文字列
;
;■戻り値	: 無し
;************************************************************************
puts:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始

		; 引数の定義
		%arg	str:qword						; // 出力文字列

		; ローカル変数の定義
		%local	buff:qword						; char buff[8];
		%local	save_rsi:qword					; void* save_rsi;

		FRAME_STACK								; // スタック領域の確保

		; レジスタの保存
		mov		[save_rsi], rsi					; // レジスタの保存

		;---------------------------------------
		; 文字列出力処理
		;---------------------------------------
		mov		rsi, rcx						; RSI = str; // インデックスの設定
		cld										; DF = 0; // アドレス加算
		mov		qword [buff], 0					; buff[7:0] = 0; // バッファをクリア
.10L:											; do
												; {
		lodsb									;   AL = *RSI++;
		cmp		al, 0							;   if (0 == AL)
		je		.10E							;     break;
												;   
		; 出力バッファに設定
		mov		[buff], al						;   buff[0] = AL;

		; 1文字出力（ユニコード）
		mov		rcx, [gTOP]						;   RCX = Instance;
		lea		rdx, [buff]						;   RDX = buff;
		mov		rax, TOP(rcx, .OutputString)	;   
		call	rax								;   OutputString();
												;   
		jmp		.10L							; }
.10E:											; 

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		mov		rsi, [save_rsi]					; // レジスタの復帰

		FRAME_END								; // フレームの終了
