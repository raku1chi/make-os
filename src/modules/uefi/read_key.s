;************************************************************************
;	キー入力待ち
;========================================================================
;■書式		: unsigned int read_key(void);
;
;■引数		: 無し
;
;■戻り値	: キーコード（32ビット）
;			: 　上位16ビット：ユニコード
;			: 　下位16ビット：スキャンコード
;************************************************************************
read_key:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始

		; ローカル変数の定義
		%local	index:qword						; int index;

		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; ローカル変数の初期化
		;---------------------------------------
		mov		qword [index], 0				; index = 0;
		mov		qword [gInputKey], 0			; gInputKey = 0;

		;---------------------------------------
		; キー入力イベント待ち
		;---------------------------------------
		mov		rcx, 1							; RCX = 1; // イベント数
		mov		rax, [gTIP]						; // キー入力イベントを取得
		lea		rdx, TIP(rax, .WaitForKey)		; RDX = &gTIP.WaitForKey
		lea		r8, [index]						; R8  = &index;
		mov		rax, [gBS]						; RAX = gBS;
		xcall	BS(rax, .WaitForEvent)			; WaitForEvent();

		;---------------------------------------
		; キーコードの取得
		;---------------------------------------
		mov		rcx, [gTIP]							; RCX = gTIP;
		lea		rdx, [gInputKey]					; RDX = &gInputKey;
		xcall	TIP(rcx, .ReadKeyStroke), rcx, rdx	; ReadKeyStroke();

		mov		rax, [gInputKey]				; return gInputKey;

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了
