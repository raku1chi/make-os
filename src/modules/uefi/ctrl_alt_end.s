;************************************************************************
;	[CTRL+ALT+END]キーの同時押下検出処理
;========================================================================
;■書式		: DWORD ctrl_alt_end(key);
;
;■引数
;	key		: 入力されたキーコード
;
;■戻り値	: [CTRL+ALT+END]キーの同時押下が検出された時、0以外の値
;************************************************************************
ctrl_alt_end:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始
		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; キー状態保存
		;---------------------------------------
		and		rcx, 0xFF						; key &= 0xFF;
		btr		rcx, 7							; CF  = key & 0x80;
		jc		.10F							; if (0 == CF)
		bts		[.key_state], rcx				; {
		jmp		.10E							;   // フラグセット
.10F:											; } else {
		btr		[.key_state], rcx				;   // フラグクリア
.10E:											; }

		;---------------------------------------
		; キー押下判定
		;---------------------------------------
												; do
												; {
		mov		rax, 0x1D						;   // [Ctrl]キーが押されているか？
		bt		[.key_state], rax				;   if ('Ctrl' != key)
		jnc		.20E							;     break;
												;     
		mov		rax, 0x38						;   // [Alt]キーが押されているか？
		bt		[.key_state], rax				;   if ('ALT' != key)
		jnc		.20E							;     break;
												;     
		mov		rax, 0x4F						;   // [End]キーが押されているか？
		bt		[.key_state], rax				;   if ('End' != key)
		jnc		.20E							;     break;
												;   
		mov		rax, -1							;   ret = -1;
												;   
.20E:											; } while (0);

		sar		rax, 8							; ret >>= 8;

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了

;========================================================================
[section .data]
ALIGN 16, db 0
.key_state:	times 32 db 0

;========================================================================
[section .text]
