;************************************************************************
;	文字列の描画
;========================================================================
;■書式		: void draw_str(x, y, color, color, str);
;
;■引数
;	x			: X座標
;	y			: Y座標
;	fg_color	: 前景色
;	bg_color	: 背景色
;	str			: 文字列のアドレス
;
;■戻り値	: 無し
;************************************************************************
draw_str:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始

		; 引数の定義
		%arg	x:qword							; // 引数の定義
		%arg	y:qword							; // 引数の定義
		%arg	fg_color:qword					; // 引数の定義
		%arg	bg_color:qword					; // 引数の定義
		%arg	str:qword						; // 引数の定義

		FRAME_STACK								; // スタック領域の確保

		; 引数の保存
		mov		[x], rcx						; // 引数を保存
		mov		[y], rdx						; // 引数を保存
		mov		[fg_color], r8					; // 引数を保存
		mov		[bg_color], r9					; // 引数を保存

		;---------------------------------------
		; 文字の描画
		;---------------------------------------
.10L:											; do
												; {
		mov		rax, [str]						;   // 文字を取得
		mov		r10b, [rax]						;   r10B = *str;
		cmp		r10b, 0							;   if (0 == r10B)
		je		.10E							;     break;

		xcall	draw_char, \
					qword [x], \
					qword [y], \
					qword [fg_color], \
					qword [bg_color], \
					r10							;   RAX = draw_char();

		add		[x], rax						;   x += RAX; // 描画した文字幅
		inc		qword [str]						;   str++;

		jmp		.10L							; } while (1);
.10E:

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了
