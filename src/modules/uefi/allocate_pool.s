;************************************************************************
;	メモリの確保
;========================================================================
;■書式		: void* allocate_pool(bytes);
;
;■引数
;	bytes	: バイト数
;
;■戻り値	: 確保したメモリへのポインタ
;************************************************************************
allocate_pool:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始

		; 引数の定義
		%arg	bytes:qword						; // 引数の定義

		; ローカル変数の定義
		%local	ptr:qword						; void* ptr;

		FRAME_STACK								; // スタック領域の確保

		; 引数の保存
		mov		[bytes], rcx					; 

		;---------------------------------------
		; メモリを確保
		;---------------------------------------
		mov		rcx, EfiLoaderData				; RCX = MemoryType;
		mov		rdx, [bytes]					; RDX = bytes;
		lea		r8, [ptr]						; R8 = &ptr;
		mov		rax, [gBS]						; 
		xcall	BS(rax, .AllocatePool)			; AllocatePool();
		cmp		rax, EFI_SUCCESS				; if (EFI_SUCCESS != RAX)
		je		.10E							; {
		mov		qword [ptr], 0					;   ptr = 0;
.10E:											; }

		mov		rax, [ptr]						; return ptr;

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了

;************************************************************************
;	メモリの解放
;========================================================================
;■書式		: void free_pool(ptr);
;
;■引数
;	ptr		: メモリのアドレス
;
;■戻り値	: 無し
;************************************************************************
free_pool:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始
		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; メモリを解放
		;---------------------------------------
												; RCX = ポインタ;
		mov		rax, [gBS]						; 
		xcall	BS(rax, .FreePool)				; FreePool();

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了
