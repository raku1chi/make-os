;************************************************************************
;	フレームバッファ情報を保存
;========================================================================
;■書式		: void get_gop_mode();
;
;■引数		: 無し
;
;■戻り値	: 無し
;************************************************************************
get_gop_mode:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始
		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; Mode情報を保存
		;---------------------------------------
		mov		rax, [gGOP]						; RAX = GOP;
		mov		rax, GOP(rax, .Mode)			; 

		mov		r8d, GOPM(rax, .MaxMode)
		mov		r9d, GOPM(rax, .Mode)
		mov		r10, GOPM(rax, .FrameBufferBase)
		mov		r11, GOPM(rax, .FrameBufferSize)

		mov		[Video.MaxMode], r8				; 
		mov		[Video.Mode], r9				; 
		mov		[Video.FrameBufferBase], r10	; 
		mov		[Video.FrameBufferSize], r11	; 

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了
