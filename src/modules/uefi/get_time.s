;************************************************************************
;	時刻の取得
;========================================================================
;■書式		: void get_time(time);
;
;■引数
;	time	: 時刻を設定する領域
;
;■戻り値	: 無し
;************************************************************************
get_time:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始
		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; 時刻の取得
		;---------------------------------------
		mov		rax, [gRT]						; 
		xcall	RT(rax, .GetTime), rcx, 0		; GetTime();

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了
