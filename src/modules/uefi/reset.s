;************************************************************************
;	システムリセット
;========================================================================
;■書式		: void reset(type);
;
;■引数
;	type	: リセットタイプ
;
;■戻り値	: 無し
;************************************************************************
reset:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始
		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; システムリセット
		;---------------------------------------
												; RCX = 引数の値;
		mov		rdx, EFI_SUCCESS				; RDX = EFI_SUCCESS;
		mov		r8, 0							; R8  = リセットデータのバイト数;
		mov		r9, 0							; R9  = リセットデータへのポインタ;
		mov		rax, [gRT]						; 
		xcall	RT(rax, .ResetSystem)			; ResetSystem();

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了
