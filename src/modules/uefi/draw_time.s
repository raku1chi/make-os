;************************************************************************
;	時刻の描画
;========================================================================
;■書式		: void draw_time(x, y);
;
;■引数
;	x		: X座標
;	y		: Y座標
;
;■戻り値	: 無し
;************************************************************************
draw_time:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始

		; 引数の定義
		%arg	x:qword							; int x;
		%arg	y:qword							; int y;

		FRAME_STACK								; // スタック領域の確保

		; レジスタの保存
		mov		[x], rcx						; // 引数を保存
		mov		[y], rdx						; // 引数を保存

		;---------------------------------------
		; 時刻の取得、変換
		;---------------------------------------
		xcall	get_time, [EfiTime]				; get_time();

		; 時を変換
		movzx	rcx, byte [EfiTime + EFI_TIME.Hour]
		xcall	itoa, rcx, [.hour], 2, 10, 4

		; 分を変換
		movzx	rcx, byte [EfiTime + EFI_TIME.Minute]
		xcall	itoa, rcx, [.min], 2, 10, 4

		; 秒を変換
		movzx	rcx, byte [EfiTime + EFI_TIME.Second]
		xcall	itoa, rcx, [.sec], 2, 10, 4

		;---------------------------------------
		; 時刻を表示
		;---------------------------------------
		mov		rcx, [x]						; RCX = X座標;
		mov		rdx, [y]						; RDX = Y座標;
		mov		r8, COLOR_TB_RECT_FG			; R8 = 前景色;
		mov		r9, COLOR_TB_RECT_BG			; R9 = 背景色;
		xcall	draw_str, rcx, rdx, r8, r9, [.time]

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了

;========================================================================
[section .data]
ALIGN 16, db 0
.time:
.hour:		db	"99", ":"
.min:		db	"99", ":"
.sec:		db	"99", 0

;========================================================================
[section .text]
