;************************************************************************
;	GOPモード情報の問い合わせ
;========================================================================
;■書式		: void* query_gop_info(mode_no);
;
;■引数
;	mode_no	: モード番号
;
;■戻り値	: GOPモード情報
;************************************************************************
query_gop_info:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始

		; ローカル変数の定義
		%local	size:qword						; int size;
		%local	info:qword						; void* info;

		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; ローカル変数の初期化
		;---------------------------------------
		mov		qword [info], 0					; info = 0;

		;---------------------------------------
		; モード取得
		;---------------------------------------
		mov		rdx, rcx						; RDX = mode_no; // 引数
		mov		rcx, [gGOP]						; RCX = GOPインスタンス;
		lea		r8, [size]						; R8 = &size;
		lea		r9, [info]						; R9 = &info;
		xcall	GOP(rcx, .QueryMode) 			; RAX = QueryMode();

		mov		rax, [info]						; return info;

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了
