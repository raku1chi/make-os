;************************************************************************
;	16進数を文字に変換
;========================================================================
;■書式		: void htoa(num, buff, size);
;
;■引数
;	num		: 変換する数値
;	buff	: 保存先バッファアドレス
;	size	: 保存先バッファサイズ
;
;■戻り値	: 無し
;************************************************************************
htoa:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始

		; 引数の定義
		%arg	num:qword						; // 引数の定義
		%arg	buff:qword						; // 引数の定義
		%arg	size:qword						; // 引数の定義

		; ローカル変数の定義
		%local	tmp:yword						; char tmp[32];

		FRAME_STACK								; // スタック領域の確保

		; 引数の保存
		mov		[num], rcx						; 変換する数値
		mov		[buff], rdx						; 保存先バッファアドレス
		mov		[size], r8						; 保存先バッファサイズ

		;---------------------------------------
		; 文字列への変換
		;---------------------------------------
		; 上位32ビット値を8バイトの文字列に変換
		shr		rcx, 32							; RCX >>= 32;
		xcall	itoa, rcx, [tmp + 0], 8, 16, 4	; itoa();

		; セパレータを追加
		mov		[tmp + 8], byte '_'				; tmp[8] = '_';

		; 下位32ビット値を8バイトの文字列に変換
		mov		rcx, [num]						; RCX = num;
		xcall	itoa, rcx, [tmp + 9], 8, 16, 4	; itoa();

		; 変換後の文字列をコピー
		lea		r8, [tmp + 17]					; R8 = &tmp[17];
		mov		r9, [buff]						; R9 = &buff[0];
		mov		rcx, [size]						; RCX = サイズ;
		add		r9, rcx							; R9 += RCX;
.10L:											; do
												; {
		dec		r8								;   R8--; // src--;
		dec		r9								;   R9--; // dst--;
		mov		al, [r8]						;   AL = *R8;
		mov		[r9], al						;   *r9 = AL;
		loop	.10L							; } while (RCX--);
.10E:

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了
