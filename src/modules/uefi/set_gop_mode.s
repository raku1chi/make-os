;************************************************************************
;	GOPモードの設定
;========================================================================
;■書式		: EFI_STATUS set_gop_mode(mode);
;
;■引数
;	mode	: モード番号
;
;■戻り値	: EFIステータス
;************************************************************************
set_gop_mode:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始
		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; モード設定
		;---------------------------------------
		mov		rdx, rcx						; RDX = mode_no; // 引数
		mov		rcx, [gGOP]						; RCX = GOPインスタンス;
		mov		rax, rcx						; 
		xcall	GOP(rax, .SetMode), rcx, rdx	; RAX = SetMode();

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了
