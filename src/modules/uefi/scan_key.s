;************************************************************************
;	キースキャン
;========================================================================
;■書式		: unsigned int scan_key(void);
;
;■引数		: 無し
;
;■戻り値	: キーコード（32ビット）
;			: 　上位16ビット：ユニコード
;			: 　下位16ビット：スキャンコード
;************************************************************************
scan_key:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始
		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; キーコードの取得
		;---------------------------------------
		mov		rcx, [gTIP]							; RCX = gTIP;
		lea		rdx, [gInputKey]					; RDX = &gInputKey;
		xcall	TIP(rcx, .ReadKeyStroke), rcx, rdx	; ReadKeyStroke();

		mov		rax, [gInputKey]				; return gInputKey;

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了
