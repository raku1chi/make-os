;************************************************************************
;	ページングの設定（タスク用）
;
;	Task.BaseAddrから2Mバイトの空間をTask.bufferに割り当てる。
;========================================================================
;■書式		: void init_page_user(task_ctrl);
;
;■引数
;	task_ctrl	: タスク管理情報
;
;■戻り値	: 無し
;************************************************************************
init_page_user:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN
		FRAME_STACK
												; RCX = task_ctrl;

		;---------------------------------------
		; タスク用バッファに仮想アドレスを設定する
		;---------------------------------------
		mov		rdx, [Task.BaseAddr]			; RDX = 仮想アドレス（変換元）;
		mov		r8, TCTRL(rcx, .buffer)			; RDX = 物理アドレス（変換先）;
		mov		r9, TCTRL(rcx, .cr3)			; RDI = PML4T;

		;---------------------------------------
		; PML4EのU/Sビットをセット
		;---------------------------------------
		mov		r10, rdx						; // PML4インデックス
		shr		r10, 39							; R10 = 仮想アドレス[47:39];
		and		r10, 0x1FF						; // 9ビットが有効

		mov		rax, [r9 + r10 * 8]				; RAX = PML4T[R10];
		or		rax, 0x07						; RAX = 0x87; // U/S=1, R/W=1, P=1
		mov		[r9 + r10 * 8], rax				; PML4T[R10] = RAX;

		;---------------------------------------
		; PDPEのU/Sビットをセット
		;---------------------------------------
		mov		r9, rax							; // PDPTを取得
		and		r9, ~0x0FFF						; R9 = PDPT;

		mov		r10, rdx						; // PDPTインデックス
		shr		r10, 30							; R10 = 仮想アドレス[38:30];
		and		r10, 0x1FF						; // 9ビットが有効

		mov		rax, [r9 + r10 * 8]				; RAX = PDPT[R10];
		or		rax, 0x07						; RAX = 0x87; // U/S=1, R/W=1, P=1
		mov		[r9 + r10 * 8], rax				; PDPT[R10] = RAX;

		;---------------------------------------
		; PDEのU/Sビットをセット
		;---------------------------------------
		mov		r9, rax							; // PDを取得
		and		r9, ~0x0FFF						; R9 = PDT;

		mov		r10, rdx						; // PDインデックス
		shr		r10, 21							; R10 = 仮想アドレス[29:21];
		and		r10, 0x1FF						; // 9ビットが有効

		or		r8, 0x87						; RAX = 0x87; // 2M=1, U/S=1, R/W=1, P=1
		mov		[r9 + r10 * 8], r8				; PDT[R10] = R8;

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END
