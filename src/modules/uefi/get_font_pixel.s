;************************************************************************
;	ピクセル情報を取得する
;========================================================================
;■書式		: int get_font_pixel(x, y, image);
;
;■引数
;	x		: X座標
;	y		: Y座標
;	image	: EFI_IMAGE_OUTPUT型へのポインタ
;
;■戻り値	: ピクセル情報
;************************************************************************
get_font_pixel:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始
		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; ピクセル情報を取得
		;---------------------------------------
		shl		rcx, 2								; RCX *= 4; // 1PX=4バイト
		shl		rdx, 5								; RDX *= 32; // 8ピクセル幅
		add		rcx, rdx							; RCX += RDX;
		add		rcx, [r8 + EFI_IMAGE_OUTPUT.Bitmap]	; RCX += Bitmap;

		mov		rax, [rcx]							; return Bitmap[RCX];

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了
