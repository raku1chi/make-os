;************************************************************************
;	数値を文字に変換
;========================================================================
;■書式		: void itoa(num, buff, size, radix, flags);
;
;■引数
;	num		: 変換する数値
;	buff	: 保存先バッファアドレス
;	size	: 保存先バッファサイズ
;	radix	: 基数（2、8、10又は16を設定する）
;	flags	: フラグ
;			:   B2 : 1=空白を'0'（ゼロ）で埋める
;			:      : 0=空白を' '（スペース）で埋める
;			:   B1 : 1=＋/-符号を表示する
;			:      : 0=＋/-符号を表示しない
;			:   B0 : 1=符号付き整数として扱う
;			:      : 0=符号無し整数として扱う
;
;■戻り値	: 無し
;************************************************************************
itoa:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始

		; 引数の定義
		%arg	num:qword						; // 引数の定義
		%arg	buff:qword						; // 引数の定義
		%arg	size:qword						; // 引数の定義
		%arg	radix:qword						; // 引数の定義
		%arg	flags:qword						; // 引数の定義

		; ローカル変数の定義
		%local	remain:qword					; int remain; // 残りバッファサイズ

		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; 引数の保存
		;---------------------------------------
		mov		[num], rcx						; 変換する数値
		mov		[buff], rdx						; バッファアドレス
		mov		[size], r8						; バッファサイズ
		mov		[radix], r9						; 基数
		mov		[remain], r8					; 残りバッファサイズ

		;---------------------------------------
		; 符号付き判定
		;---------------------------------------
		test	qword [flags], 0b0001			; if (flags & 0x01) // 符号付き
.10Q:	je		.10E							; {
		cmp		qword [num], 0					;   if (num < 0)
.12Q:	jge		.12E							;   {
		or		qword [flags], 0b0010			;     flags |=  2; // 符号表示
.12E:											;   }
.10E:											; }

		;---------------------------------------
		; 符号出力判定
		;---------------------------------------
		test	qword [flags], 0b0010			; if (flags & 0x02) // 符号出力判定
.20Q:	je		.20E							; {
		mov		rax, [buff]						;   dst = &buff[0]; // 符号表示
		cmp		qword [num], 0					;   if (num < 0)
.22Q:	jge		.22F							;   {
		neg		qword [num]						;     num *= -1;    // 符号反転
		mov		byte [rax], '-'					;     *dst = '-';
		jmp		.22E							;   }
.22F:											;   else
												;   {
		mov		byte [rax], '+'					;     *dst = '+';
.22E:											;   }
		dec		qword [remain]					;   size--;         // 残りバッファサイズの減算
.20E:											; }

		;---------------------------------------
		; ASCII変換
		;---------------------------------------
		mov		rax, [num]						; RAX  = num;
		mov		rcx, [remain]					; RCX  = 残りバッファサイズ;
		mov		r8, [buff]						; dst  = &buff[0];
		add		r8, [size]						; dst += size;
.30L:											; do
												; {
		mov		rdx, 0							;   
		div		qword [radix]					;   RDX = RDX:RAX % 基数;
												;   RAX = RDX:RAX / 基数;
												;   
		mov		dl, [.ascii + rdx]				;   DL  = ASCII[RDX];
												;   
		dec		r8								;   dst--;
		mov		[r8], dl						;   *dst = DL;
												;   
		cmp		rax, 0							;   ZF = (RAX == 0);
		loopnz	.30L							; } while (--RCX && !ZF);
.30E:

		;---------------------------------------
		; 空欄を埋める
		;---------------------------------------
		cmp		rcx, 0							; if (残りバッファサイズ)
.40Q:	je		.40E							; {
		mov		dl, ' '							;   DL = ' ';         // ' 'で埋める（デフォルト値）
												;   
		test	qword [flags], 0b0100			;   if (flags & 0x04) // '0'で埋める
		cmovnz	dx, [.ascii]					;     DX = ASCII[0];
												;   
												;   do
.42L:											;   {
		dec		r8								;     dst--;
		mov		[r8], dl						;     *dst = DL;
		loopnz	.42L							;   } while (--RCX && !ZF)
.40E:											; }

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了

.ascii	db		"0123456789ABCDEF"				; 変換テーブル
