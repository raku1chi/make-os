;************************************************************************
;	矩形の描画
;========================================================================
;■書式		: void draw_rect(X0, Y0, X1, Y1, color);
;
;■引数
;	X0		: 始点のX座標
;	Y0		: 始点のY座標
;	X1		: 終点のX座標
;	Y1		: 終点のY座標
;	color	: 描画色
;
;■戻り値	: 無し
;************************************************************************
draw_rect:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始

		%arg	x0:qword						; // 引数の定義
		%arg	y0:qword						; // 引数の定義
		%arg	x1:qword						; // 引数の定義
		%arg	y1:qword						; // 引数の定義
		%arg	color:qword						; // 引数の定義

		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; 座標軸の大小を確定
		;---------------------------------------
		cmp		rcx, r8							; if (X1 < X0)
		jl		.10E							; {
		xchg	rcx, r8							;   // X0とX1を入れ替える;
.10E:											; }

		cmp		rdx, r9							; if (Y1 < Y0)
		jl		.20E							; {
		xchg	rdx, r9							;   // Y0とY1を入れ替える;
.20E:											; }

		; 引数の保存
		mov		[x0], rcx						; // 引数の保存
		mov		[y0], rdx						; // 引数の保存
		mov		[x1], r8						; // 引数の保存
		mov		[y1], r9						; // 引数の保存

		;---------------------------------------
		; 矩形を描画
		;---------------------------------------
		xcall	draw_line, \
					qword [x0], qword [y0], \
					qword [x1], qword [y0], \
					qword [color] 				; 上線
		xcall	draw_line, \
					qword [x0], qword [y0], \
					qword [x0], qword [y1], \
					qword [color] 				; 左線

		dec		qword [y1]						; y1--; // 下線は1ドット上げる
		xcall	draw_line, \
					qword [x0], qword [y1], \
					qword [x1], qword [y1], \
					qword [color] 				; 下線
		inc		qword [y1]						; y1++; // 元の値に戻す

		dec		qword [x1]						; x1--; // 右線は1ドット左に移動
		xcall	draw_line, \
					qword [x1], qword [y0], \
					qword [x1], qword [y1], \
					qword [color] 				; 右線

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了
