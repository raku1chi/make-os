;************************************************************************
;	矩形の塗りつぶし
;========================================================================
;■書式		: void fill_rect(X0, Y0, X1, Y1, color);
;
;■引数
;	X0		: 始点のX座標
;	Y0		: 始点のY座標
;	X1		: 終点のX座標
;	Y1		: 終点のY座標
;	color	: 描画色
;
;■戻り値	: 無し
;************************************************************************
fill_rect:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始

		; 引数の定義
		%arg	x0:qword						; // 引数の定義
		%arg	y0:qword						; // 引数の定義
		%arg	x1:qword						; // 引数の定義
		%arg	y1:qword						; // 引数の定義
		%arg	color:qword						; // 引数の定義

		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; 座標軸の大小を確定
		;---------------------------------------
		cmp		rcx, r8							; if (X1 < X0)
		jl		.10E							; {
		xchg	rcx, r8							;   // X0とX1を入れ替える;
.10E:											; }

		cmp		rdx, r9							; if (Y1 < Y0)
		jl		.20E							; {
		xchg	rdx, r9							;   // Y0とY1を入れ替える;
.20E:											; }

		; 引数の保存
		mov		[x0], rcx						; // 引数の保存
		mov		[y0], rdx						; // 引数の保存
		mov		[x1], r8						; // 引数の保存
		mov		[y1], r9						; // 引数の保存

		;---------------------------------------
		; 横線で塗りつぶす
		;---------------------------------------
.30L:	mov		rcx, [y0]						; // 高さ分繰り返し
		cmp		rcx, [y1]						; while (y0 < y1)
		jae		.30E							; {
												;   
		xcall	draw_line, \
					qword [x0], \
					qword [y0], \
					qword [x1], \
					qword [y0], \
					qword [color]				;   draw_line();
												;   
		inc		qword [y0]						;   y0++;
		jmp		.30L							;   
.30E:											; }

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了
