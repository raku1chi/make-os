;************************************************************************
;	sin
;========================================================================
;■書式		: void sin(rad);
;
;■引数
;	rad		: 角度
;
;■戻り値	: sin
;************************************************************************
sin:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始
		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; ±2πの範囲に収める(-2π < x < 2π)
		;---------------------------------------
		movsd	xmm1, xmm0						; // 2πで除算
		movsd	xmm2, [math.2_pi]				; XMM2 = 2π;
		divsd	xmm1, xmm2						; XMM1 = X / 2π;

		cvtsd2si	rax, xmm1					; // 整数部を取得
		cvtsi2sd	xmm1, rax					; XMM1 = (int)XMM1;

		mulsd	xmm1, xmm2						; XMM1 *= 2π;
		subsd	xmm0, xmm1						; XMM0 -= XMM1;

		;---------------------------------------
		; 初期設定
		; 
		;     (-1)^n * X^(2n+1)
		; Σ  -------------------
		;          (2n+1)!
		; 
		;        XMM1 * XMM2^2
		; Σ  -------------------
		;    (XMM3+1) * (XMM3+2)
		; 
		;---------------------------------------
		movsd	xmm1, xmm0						; XMM1 = X; // 初項

		mov		rax, -1							; // 乗算値を設定
		cvtsi2sd xmm2, rax						; XMM2 = -1; // -1
		mulsd	xmm2, xmm0						; XMM2 *= X; // -X
		mulsd	xmm2, xmm0						; XMM2 *= X; // -X^2

		mov		rax, 1							; // 除算値を設定
		cvtsi2sd xmm3, rax						; XMM3 = 1; // nの初期値
		movsd	xmm4, xmm3						; XMM4 = 1; // nの加算値

		;---------------------------------------
		; 繰り返し処理
		; x - x^3/3! + x^5/5! - x^7/7! ...
		;---------------------------------------
		mov		rcx, 9							; RCX = 9;
.10L:											; do
												; {
		; -(X^2)を乗算（分子）
		mulpd	xmm1, xmm2						;   XMM1 *= XMM2;

		; n!で除算（分母）
		addsd	xmm3, xmm4						;   XMM3 += 1.0;
		divsd	xmm1, xmm3						;   XMM1 /= XMM3;
		addsd	xmm3, xmm4						;   XMM3 += 1.0;
		divsd	xmm1, xmm3						;   XMM1 /= XMM3;

		; 値を更新
		addsd	xmm0, xmm1						;   XMM0 += XMM1;   // 現在値を更新

		loop	.10L							; } while (--RCX);

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了

ALIGN 16, db 0
math:
.2_pi:		dq	6.28318530718, 0
.pi_2:		dq	1.57079632679, 0

;************************************************************************
;	cos
;========================================================================
;■書式		: void cos(rad);
;
;■引数
;	rad		: 角度
;
;■戻り値	: cos
;************************************************************************
cos:
		;---------------------------------------
		; cos(θ) = sin(θ+π/2)
		;---------------------------------------
		addsd	xmm0, [math.pi_2]				; θ += π/2;
		jmp		sin								; sin();
