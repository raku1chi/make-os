;************************************************************************
;	GUIDに一致した最初のプロトコルを取得する
;========================================================================
;■書式		: void* get_protocol(guid);
;
;■引数
;	guid	: GUIDへのポインタ
;
;■戻り値	: プロトコルのインスタンス
;************************************************************************
get_protocol:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始

		; ローカル変数の定義
		%local	interface:qword					; void* interface;

		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; GUIに対応した最初のプロトコルを取得
		;---------------------------------------
												; RCX = guid;
		mov		rdx, 0							; RDX = 0;
		lea		r8, [interface]					; R8 = &interface;
		mov		rax, [gBS]						; 
		xcall	BS(rax, .LocateProtocol)		; RAX = LocateProtocol();
		cmp		rax, EFI_SUCCESS				; if (EFI_SUCCESS != RAX)
		je		.10E							; {
		mov		qword [interface], 0			;   interface = 0;
.10E:											; }

		mov		rax, [interface]				; return interface;

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了
