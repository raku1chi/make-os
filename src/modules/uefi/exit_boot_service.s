;************************************************************************
;	ブートサービスの終了
;========================================================================
;■書式		: int exit_boot_service();
;
;■引数		: 無し
;
;■戻り値	: 成功(0以外)、失敗(0)
;************************************************************************
exit_boot_service:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始
		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; ブートサービスの終了
		;---------------------------------------
		mov		rax, [gBS]						; 
		xcall	BS(rax, .ExitBootServices), \
					qword [gImageHandle], \
					qword [MemoryMap.MapKey]	; RAX = ExitBootServices();
		cmp		rax, EFI_SUCCESS				; return EFI_SUCCESS != RAX;
		sete	al								; 
		movzx	rax, al							; 

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了
