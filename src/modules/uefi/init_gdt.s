;************************************************************************
;	GDTの初期化
;========================================================================
;■書式		: void init_gdt(void);
;
;■引数		: 無し
;
;■戻り値	: 無し
;************************************************************************
init_gdt:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始
		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; GDTの再設定
		;---------------------------------------
		lgdt	[NEW_GDTR]						; 

		;---------------------------------------
		; CSの再設定
		;---------------------------------------
		mov		rcx, rsp						; RCX = RSP; // RSPの値を保存
		lea		rdx, [.NEW_CS]					; RDX = .NEW_CS;

		push	DS_KERNEL						; +40 : SS
		push	rcx								; +32 : RSP
		pushf									; +24 : EFLAGS
		push	CS_KERNEL						; +16 : CS
		push	rdx								; + 8 : RIP
		iretq									; iret();

.NEW_CS:
		mov		ax, ss							; 
		mov		ds, ax							; 
		mov		es, ax							; 
		mov		fs, ax							; 
		mov		gs, ax							; 

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了
