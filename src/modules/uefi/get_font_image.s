;************************************************************************
;	フォント情報を取得する
;========================================================================
;■書式		: void get_font_image(char, image);
;
;■引数
;	char	: 文字コード
;	image	: EFI_IMAGE_OUTPUT型へのポインタ
;
;■戻り値	: 無し
;************************************************************************
get_font_image:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始
		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; フォントアドレスを取得
		;---------------------------------------
		mov		rax, [FONT]						; RAX = FONT;
		and		rcx, 0x7F						; RCX &= 0x7F;
		mov		rcx, [rax + rcx * 8]			; RCX = FONT[RCX];

		;---------------------------------------
		; EFI_IMAGE_OUTPUT構造体に設定
		;---------------------------------------
		mov		r8, [rcx + 0]					; *image = *RCX;
		mov		r9, [rcx + 8]					; 
		mov		[rdx + 0], r8					; 
		mov		[rdx + 8], r9					; 

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了
