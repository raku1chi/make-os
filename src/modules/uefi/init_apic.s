;************************************************************************
;	APICの初期化
;========================================================================
;■書式		: void init_apic(void);
;
;■引数		: 無し
;
;■戻り値	: 無し
;************************************************************************
init_apic:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		FRAME_BEGIN								; // フレームの開始
		FRAME_STACK								; // スタック領域の確保

		;---------------------------------------
		; APICの設定
		;---------------------------------------
		mov		r8, [APIC.Base]					; // APICベースアドレスを設定
		mov		LAPIC(r8, .ICR), 0				; ICR = 0; // カウント停止
		mov		LAPIC(r8, .LVT_TR), 0x0001_0000	; Mask = 1; // 割り込みマスク

		; 割り込みベクタの設定
		set_idt	0x30, int_timer					; // APICタイマーの設定

		; カウント開始
		mov		r8, [APIC.Base]					; // APICベースアドレスを設定
		mov		LAPIC(r8, .LVT_TR), 0x0002_0030	; Mode = Periodic; // 周期モード
												; Vector = 0x30; // int_apic_timer;
		mov		rdx, 0							; RDX = 0
		mov		rax, [Timer.Interval]			; RAX = Interval;
		mov		rcx, 100						; RCX = 100;
		idiv	rcx								; RAX = RDX:RAX / RCX;
		mov		LAPIC(r8, .ICR), eax			; ICR = Interval; // カウント開始

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		FRAME_END								; // フレームの終了
