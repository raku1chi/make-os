;************************************************************************
;	syscallの初期化
;========================================================================
;■書式		: void init_syscall(void);
;
;■引数		: 無し
;
;■戻り値	: 無し
;************************************************************************
init_syscall:
		;---------------------------------------
		; 【スタックフレームの構築】
		;---------------------------------------
		%push									; // コンテキストの設定
		%stacksize	flat64						; // スタック幅を設定
		%assign		%$localsize (8 * 6)			; // スタック数を初期化

		; スタックの調整
		push	rbp								; // RBPを保存
		mov		rbp, rsp						; // RBPの再設定

		; スタック領域の確保
		sub		rsp, %$localsize				; // スタック領域の確保
		and		rsp, ~0x0F						; // 16バイト境界に設定

		;---------------------------------------
		; IA32_EFER.SCEビットをセット
		;---------------------------------------
		mov		ecx, 0xC000_0080				; 
		rdmsr									; 
		or		rax, 1							; SCE = 1;
		wrmsr									; WRMSR();

		;---------------------------------------
		; IA32_STAR STAR[63:48]=CS/SS(sysret)
		;---------------------------------------
		mov		edx, ((0x0018 | 3) << 16) | 0x0008
		mov		eax, 0							; 
		mov		rcx, 0xC000_0081				; 
		wrmsr									; WRMSR();

		;---------------------------------------
		; LSTAR
		;---------------------------------------
		lea		rdx, [int_syscall]				; LSTAR = int_syscall;
		mov		eax, edx						; 
		shr		rdx, 32							; 
		mov		rcx, 0xC000_0082				; 
		wrmsr									; WRMSR();

		;---------------------------------------
		; SFMASK
		;---------------------------------------
		mov		edx, 0							; 
		mov		eax, 0x0200						; SFMASK.IF = 1;
		mov		rcx, 0xC000_0084				; 
		wrmsr									; WRMSR();

		;---------------------------------------
		; 【スタックフレームの破棄】
		;---------------------------------------
		mov		rsp, rbp						; // RSPの復帰
		pop		rbp								; // RBPの復帰
		ret
		%pop

