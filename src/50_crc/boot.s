;************************************************************************
;	BIOSでロードされる最初のセクタ
;	
;	プログラム全体を通して、セグメントの値は0x0000とする。
;	(DS==ES==0)
;	
;************************************************************************
		BOOT_LOAD	equ		0x7C00				; ブートプログラムのロード位置

		ORG		BOOT_LOAD						; ロードアドレスをアセンブラに指示

;************************************************************************
;	マクロ
;************************************************************************
%include	"../include/macro.s"

;************************************************************************
;	エントリポイント
;************************************************************************
entry:
		;---------------------------------------
		; BPB(BIOS Parameter Block)
		;---------------------------------------
		jmp		ipl								; IPLへジャンプ
		times	90 - ($ - $$) db 0x90			; 

		;---------------------------------------
		; IPL(Initial Program Loader)
		;---------------------------------------
ipl:
		cli										; // 割り込み禁止

		mov		ax, 0x0000						; AX = 0x0000;
		mov		ds, ax							; DS = 0x0000;
		mov		es, ax							; ES = 0x0000;
		mov		ss, ax							; SS = 0x0000;
		mov		sp, BOOT_LOAD					; SP = 0x7C00;

		sti										; // 割り込み許可

		mov		[BOOT.DRIVE], dl				; ブートドライブを保存

		;---------------------------------------
		; ファイル全体を読み込む
		;---------------------------------------
		mov		ah, 0x02						; AH = 読み込み命令
		mov		al, (FILE_END - CRC_DATA) / 512	; AL = 読み込みセクタ数
		mov		cx, 0x0002						; CX = シリンダ/セクタ
		mov		dh, 0x00						; DH = ヘッド位置
		mov		dl, [BOOT.DRIVE]				; DL = ドライブ番号
		mov		bx, 0x7C00 + 512				; BX = オフセット
		int		0x13							; if (CF = BIOS(0x13, 0x02))
.10Q:	jnc		.10E							; {
.10T:	cdecl	puts, .e0						;	puts(.e0);
		jmp		$								;   while (1) ; // 無限ループ
.10E:											; }

		;---------------------------------------
		; CRC32の計算
		;---------------------------------------
		mov		si, CRC_DATA					; SI = CRCデータの先頭;
		mov		cx, CRC_DATA_SIZE				; CX = CRCデータのバイト数;
		lodsd									; CRC = *DATA++; // 先頭の4バイト
												;
		not		eax								; // 初期値を反転
		mov		ebx, eax						; EBX = ~EAX;
												; 
.20L:											; do
												; {
		lodsb									;   AL = *SI; // 1バイト分のデータ
		mov		dx, cx							;   DX = CX;  // ループカウンタを保存
		mov		cx, 8							;   CX = 8;   // 8ビット分のカウント
.22L:											;   do
												;   {
		shr		al, 1							;     // AL:EBX 全体を右シフト
		rcr		ebx, 1							;     CY = LSB;
		jnc		.24E							;     if (CY)
												;     {
		xor		ebx, 0xEDB88320					;       EBX ^= 生成多項式;
.24E:											;     }
		loop	.22L							;   } while (--CX);
												;   
		mov		cx, dx							;   CX = DX; // ループカウンタを復帰
		loop	.20L							; } while (--CX);
.20E:											; 
												; 
		not		ebx								; // 結果を反転

		;---------------------------------------
		; 計算結果を表示
		;---------------------------------------
		cdecl	itoa,  bx, .s3, 4, 16, 0b0100	; // 下位16ビットを設定
		shr		ebx, 16							; EBX >>= 16;
		cdecl	itoa,  bx, .s2, 4, 16, 0b0100	; // 上位16ビットを設定
		cdecl	itoa,  CRC_DATA_SIZE, .s4, 4, 16, 0b0100	; // データサイズを設定
		cdecl	puts, .s1						; // 結果を表示

		;---------------------------------------
		; 処理の終了
		;---------------------------------------
		jmp		$								; while (1) ; // 無限ループ

		;---------------------------------------
		; データ
		;---------------------------------------
.e0		db	"Error:sector read", 0

.s1		db	"CRC32:0x"
.s2		db	"----"
.s3		db	"----", 0x0D, 0x0A, "SIZE :0x"
.s4		db	"----", 0x0D, 0x0A, 0

ALIGN 2, db 0
BOOT:											; ブートドライブに関する情報
.DRIVE:			dw	0							; ドライブ番号

;************************************************************************
;	モジュール
;************************************************************************
%include	"../modules/real/puts.s"
%include	"../modules/real/itoa.s"

;************************************************************************
;	ブートフラグ（先頭512バイトの終了）
;************************************************************************
		times	510 - ($ - $$) db 0x00
		db	0x55, 0xAA

;************************************************************************
;	CRCデータ
;************************************************************************
CRC_DATA:
		CRC_DATA_SIZE			equ		(CRC_DATA_END - CRC_DATA)
		db	1, 2, 3, 4, 5						; CRC32:0x470B99F4
CRC_DATA_END:

ALIGN 512, db 0
FILE_END:
